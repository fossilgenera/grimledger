import { Project } from "../../domain/models/project";
import { PRIORITIES, PROJECT_STATUSES } from "../../domain/types";
import { noteNameOf } from "../VaultLayout";
import { describeValue, isOneOf, readBooleanDefaultFalse, readOptionalIsoDate } from "./fields";
import { fail, Result, ok } from "../../domain/result";
import { parseWikilinkTarget } from "./wikilink";

type Frontmatter = Readonly<Record<string, unknown>> | undefined;

/** A `Project` whose client is still an unresolved link target. */
export type ProjectRecord = Omit<Project, "client"> & { clientLinkPath: string };

export function projectFromFrontmatter(path: string, frontMatter: Frontmatter): Result<ProjectRecord> {
  if (frontMatter?.["type"] !== "project") {
    return fail('Not a project note: "type" is not "project"');
  }

  const clientLinkPath = parseWikilinkTarget(frontMatter["client"]);
  if (clientLinkPath === undefined) {
    return fail(`Invalid client link: ${describeValue(frontMatter?.["client"])}`);
  }

  const status = frontMatter["status"];
  const priority = frontMatter["priority"];
  const startDate = readOptionalIsoDate(frontMatter["start_date"]);
  const currentFocus = readBooleanDefaultFalse(frontMatter["current_focus"], "current_focus");

  if (!isOneOf(PROJECT_STATUSES, status)) {
    return fail(`Invalid status ${describeValue(status)}`);
  }
  if (!isOneOf(PRIORITIES, priority)) {
    return fail(`Invalid priority ${describeValue(priority)}`);
  }
  if (!startDate.ok) {
    return fail(`Invalid startDate ${describeValue(frontMatter?.["start_date"])}: ${startDate.reason}`);
  }
  if (!currentFocus.ok) {
    return currentFocus;
  }

  return ok({
    path,
    name: noteNameOf(path),
    clientLinkPath,
    status,
    priority,
    startDate: startDate.value,
    currentFocus: currentFocus.value,
  });
}

export interface ProjectWriteInput {
    /** A ready-made wikilink string such as "[[ABC Bank]]", generated by the repo */
    clientLink: string;
    status: Project["status"];
    priority: Project["priority"];
    startDate: Project["startDate"];
    currentFocus: boolean;
}

/** Only the properties this plugin owns. */
export function projectToFrontmatter(input: ProjectWriteInput): Record<string, unknown> {
    const result: Record<string, unknown> = {
        type: "project",
        client: input.clientLink,
        status: input.status,
        priority: input.priority,
        current_focus: input.currentFocus,
    };
    if (input.startDate !== undefined) {
        result["start_date"] = input.startDate;
    }
    return result;
}